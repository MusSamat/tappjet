// Единый стандарт госномера КР для всех форм (гараж + верификация):
// ввод нормализуется (верхний регистр, только латиница и цифры), валиден
// 4–10 символов. Покрывает и стандарт 2016+ (01KG123ABC), и старые номера.
export const PLATE_REGEX = /^[A-Z0-9]{4,10}$/;

export const normalizePlate = (v: string): string =>
  v.toUpperCase().replace(/[^A-Z0-9]/g, '');
